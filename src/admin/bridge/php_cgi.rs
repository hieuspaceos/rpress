/// Seatbelt profile for `sandbox-exec` (macOS, built-in). Deny-everything
/// default; PHP needs its own binary+libs (system dirs), the docroot tree
/// (read), wp-content/database + site www (read-write for sqlite/uploads),
/// and loopback so `php -S` can bind + answer. mu-plugins is read-only —
/// every file inside it is host-written at spawn (audit M1b: a writable
/// mu-plugins dir is persistent PHP-code exec across spawns). Everything
/// else — home dir, .env/dump.sql/rpress.db, outbound net — is denied.
/// SBPL params: {docroot}, {www}, {templates}, {db}.
/// Proven on macOS 26: `process-exec` without `*` never matches php's
/// spawn; `network*` alone allows outbound — deny+re-allow loopback.
const SANDBOX_PROFILE: &str = r#"(version 1)
(deny default)
(import "system.sb")
(allow network*)
(deny network-outbound (remote ip "*:*"))
(allow network-outbound (remote ip "localhost:*"))
(allow file-read*
{parents}
    (subpath "{db}")
    (subpath "{docroot}")
    (subpath "{www}")
    (subpath "{templates}")
    (subpath "/opt/homebrew")
    (subpath "/usr")
    (subpath "/System")
    (subpath "/private/etc")
    (subpath "/Library")
    (subpath "/private/tmp")
    ;; macOS resolves /var -> /private/var before matching; TMPDIR
    ;; (/var/folders/_x/.../T) is really /private/var/folders — without
    ;; this every POST big enough to need a tempfile is discarded and
    ;; admin-ajax dies 400 ("POST data can't be buffered").
    (subpath "/private/var/folders")
    (subpath "/dev")
    (literal "/dev/null"))
(allow file-write*
    (subpath "{db}")
    (subpath "{uploads}")
    (subpath "/private/tmp")
    (subpath "/private/var/folders")
    (subpath "/dev"))
(allow process-exec*)
(allow process-fork)
(allow sysctl-read)
(allow mach-lookup)
"#;

/// Wrap a Command in `sandbox-exec` when available; returns `None` where
/// neither Seatbelt nor bwrap exists. Callers fail CLOSED on `None` —
/// a bare `php -S` needs the explicit `RPRESS_BRIDGE_UNSAFE=1` opt-in.
fn sandboxed(php: &Path, docroot: &Path, www: &Path, templates: &Path, db_dir: &Path) -> Option<Command> {
    let se = PathBuf::from("/usr/bin/sandbox-exec");
    if se.is_file() {
        return sandboxed_seatbelt(&se, php, docroot, www, templates, db_dir);
    }
    // Linux: bubblewrap gives the same shape — ro-bind everything the child
    // needs, rw-bind only db/uploads, no host fs beyond the list.
    if let Some(bw) = which_bwrap() {
        return Some(sandboxed_bwrap(&bw, php, docroot, www, templates, db_dir));
    }
    None
}

/// `bwrap` on PATH or the usual sbin locations.
fn which_bwrap() -> Option<PathBuf> {
    for c in ["bwrap", "/usr/bin/bwrap", "/usr/local/bin/bwrap", "/bin/bwrap"] {
        let p = PathBuf::from(c);
        // PATH lookup for bare name; absolute candidates are checked as files.
        if !c.contains('/') {
            if let Ok(o) = std::process::Command::new("sh").args(["-c", "command -v bwrap"]).output() {
                if o.status.success() {
                    let path = String::from_utf8_lossy(&o.stdout).trim().to_string();
                    if !path.is_empty() {
                        return Some(PathBuf::from(path));
                    }
                }
            }
        } else if p.is_file() {
            return Some(p);
        }
    }
    None
}

/// Linux equivalent of the Seatbelt profile: mount-namespace confinement.
/// Everything the child needs is ro-bound; only wp.db and uploads are
/// writable — mu-plugins is read-only (host-written at spawn, audit M1b).
/// `--share-net` keeps host loopback so the
/// rpress proxy can reach `php -S 127.0.0.1:<port>`. True loopback-only
/// isolation is NOT achievable here without root: `--unshare-net` would
/// kill host→child reachability entirely (rpress proxies into the child's
/// netns), while slirp4netns/pasta ADD outbound NAT — the opposite of
/// egress restriction. Egress is confined at the service level instead:
/// the generated systemd unit carries `IPAddressAllow=localhost
/// IPAddressDeny=any` (install.sh). The in-namespace fence is the fs
/// mount table + per-spawn token + pull whitelist.
fn sandboxed_bwrap(bw: &Path, php: &Path, docroot: &Path, www: &Path, templates: &Path, db_dir: &Path) -> Command {
    let uploads = www.join("wp-content/uploads");
    let mut c = Command::new(bw);
    c.args([
        // pid/ipc isolation; share host net (loopback needed for the proxy)
        "--unshare-pid", "--unshare-ipc", "--unshare-uts", "--share-net",
        "--die-with-parent", "--new-session",
        // minimal root: real system dirs read-only where present
        "--ro-bind", "/usr", "/usr",
        "--ro-bind-try", "/lib", "/lib",
        "--ro-bind-try", "/lib64", "/lib64",
        "--ro-bind-try", "/opt", "/opt",
        "--ro-bind-try", "/etc", "/etc",
        "--dev", "/dev",
        "--tmpfs", "/tmp",
    ]);
    let ro = |c: &mut Command, p: &Path| {
        if p.exists() {
            c.arg("--ro-bind").arg(p).arg(p);
        }
    };
    ro(&mut c, php);
    ro(&mut c, docroot);
    ro(&mut c, templates);
    // www read-only EXCEPT the two writable subtrees, bound after.
    // mu-plugins stays read-only (host owns every file in it — audit M1b).
    ro(&mut c, www);
    for p in [db_dir, &uploads] {
        std::fs::create_dir_all(p).ok();
        c.arg("--bind").arg(p).arg(p);
    }
    c.arg("--").arg(php);
    c
}

fn sandboxed_seatbelt(se: &Path, php: &Path, docroot: &Path, www: &Path, templates: &Path, db_dir: &Path) -> Option<Command> {
    // SQLite stats every parent of its db file — a `subpath` grant covers
    // leaves only; ancestors need explicit `literal` lines or PDO open fails.
    let mut parents = String::new();
    let mut p = db_dir.parent();
    let mut chain = Vec::new();
    while let Some(d) = p {
        chain.push(d.display().to_string());
        p = d.parent();
    }
    for d in chain.iter().rev() {
        parents.push_str(&format!("    (literal \"{d}\")\n"));
    }
    let profile = SANDBOX_PROFILE
        .replace("{php}", &php.display().to_string())
        .replace("{docroot}", &docroot.display().to_string())
        .replace("{www}", &www.display().to_string())
        .replace("{templates}", &templates.display().to_string())
        .replace("{db}", &db_dir.display().to_string())
        .replace("{uploads}", &www.join("wp-content/uploads").display().to_string())
        .replace("{parents}", &parents);
    let pf = docroot.join(".sandbox.sb");
    std::fs::write(&pf, profile).ok()?;
    let mut cmd = Command::new(se);
    cmd.arg("-f").arg(&pf);
    cmd.arg(php);
    Some(cmd)
}

pub(crate) fn spawn(
    _site: &str,
    slug: &str,
    www: &Path,
    rpress_db: &Path,
    post_id: Option<i64>,
    plugin_file: &str,
    templates: &Path,
) -> Result<BridgeState> {
    let _t0 = Instant::now();
    // Canonicalize: sandbox profile rules and `php -S -t` both resolve
    // against the child's cwd — relative `--www`/`--templates` silently
    // deny the docroot or spawn a dead docroot.
    let www = &std::fs::canonicalize(www).unwrap_or_else(|_| www.to_path_buf());
    let rpress_db = &std::fs::canonicalize(rpress_db).unwrap_or_else(|_| rpress_db.to_path_buf());
    let templates = &std::fs::canonicalize(templates).unwrap_or_else(|_| templates.to_path_buf());
    let php = php_bin().ok_or_else(|| anyhow::anyhow!("php not on PATH — install php-cli or keep RuntimeKind::Playground"))?;
    let wp_core = templates.join("wp-core");

    let dir = www.join("bridge").join(slug);
    // Per-site+slug nonce secret persisted OUTSIDE <slug> — the dir below
    // is wiped every spawn; wp.db salts must stay stable or an open
    // editor's nonces fail check_ajax_referer on the next respawn.
    let secret_file = www.join("bridge").join(format!(".secret-{slug}"));
    let secret = match std::fs::read_to_string(&secret_file) {
        Ok(s) if s.trim().len() >= 32 => s.trim().to_string(),
        _ => {
            let s = format!("{:x}{:x}", rand::random::<u128>(), rand::random::<u128>());
            let _ = std::fs::write(&secret_file, &s);
            s
        }
    };
    if dir.exists() {
        std::fs::remove_dir_all(&dir).with_context(|| format!("wipe {}", dir.display()))?;
    }
    let docroot = dir.join("docroot");
    let wp_content = www.join("wp-content");

    // WP core projection: `wp-includes` is symlinked (require'd via the
    // ABSPATH path string — cheap, ~1.8s saved vs cp_r). `wp-admin` must
    // stay a REAL dir of hardlinked files: PHP resolves __FILE__ through
    // symlinks, so a symlinked wp-admin makes ABSPATH point at
    // templates/wp-core — wp-config.php disappears and every request
    // redirects to setup-config.php.
    std::fs::create_dir_all(&docroot)?;
    for e in std::fs::read_dir(&wp_core)?.flatten() {
        let name = e.file_name();
        if name == "wp-config.php" || name == "wp-config-sample.php" || name == "wp-content" {
            continue; // rendered by us / projected below
        }
        let (s, d) = (e.path(), docroot.join(&name));
        if name == "wp-includes" {
            symlink_dir(&s, &d)?;
        } else if e.file_type()?.is_dir() {
            cp_r(&s, &d)?;
        } else {
            // Copy — never hard link: see cp_r; a shared inode lets docroot
            // writes truncate the vendored template.
            std::fs::copy(&s, &d)?;
        }
    }
    let content = docroot.join("wp-content");
    std::fs::create_dir_all(&content)?;
    // `templates/wp-core/wp-content` ships empty placeholder dirs —
    // they collide with the symlink farm below; drop everything but
    // index.php before laying links.
    if let Ok(entries) = std::fs::read_dir(&content) {
        for e in entries.flatten() {
            if e.file_name() != "index.php" {
                let p = e.path();
                if p.is_dir() {
                    std::fs::remove_dir_all(&p).ok();
                } else {
                    std::fs::remove_file(&p).ok();
                }
            }
        }
    }

    // wp-content children: per-subdir symlink like the playground mounts —
    // wholesale wp-content symlink would shadow db.php drop-in + database/.
    if let Ok(entries) = std::fs::read_dir(&wp_content) {
        for e in entries.flatten() {
            let name = e.file_name().to_string_lossy().to_string();
            if matches!(name.as_str(), "plugins" | "themes") {
                let dst_parent = content.join(&name);
                std::fs::create_dir_all(&dst_parent)?;
                if let Ok(kids) = std::fs::read_dir(e.path()) {
                    for k in kids.flatten() {
                        symlink_dir(&k.path(), &dst_parent.join(k.file_name()))?;
                    }
                }
            // `mu-plugins` is owned below (token fence + shims) — skip the
            // wholesale symlink or the create/write into it collides.
            } else if e.path().is_dir() && name != "database" && name != "mu-plugins" {
                symlink_dir(&e.path(), &content.join(&name))?;
            }
        }
    }
    // Bundled plugin fallback (same rule as playground: site copy wins).
    if let Some(bundle) = plugin_file.split('/').next() {
        let plugins_dir = content.join("plugins");
        std::fs::create_dir_all(&plugins_dir)?;
        if !wp_content.join("plugins").join(bundle).exists() {
            let bundled = templates.join("wp-plugins").join(bundle);
            if bundled.is_dir() {
                symlink_dir(&bundled, &plugins_dir.join(bundle))?;
            }
        }
    }

    // mu-plugins: site's rpress-bridge.php (token fence) + our shims.
    let mu = content.join("mu-plugins");
    std::fs::create_dir_all(&mu)?;
    std::fs::write(mu.join("rpress-bridge.php"), MU_PLUGIN)?;
    std::fs::write(mu.join("rpress-admin.php"), ADMIN_MU)?;
    std::fs::write(mu.join("rpress-sqlite.php"), SQLITE_MU)?;
    // Vendored sqlite impl — the drop-in resolves `$p/wp-includes/sqlite/db.php`.
    symlink_dir(&templates.join("wp-sqlite").join("sqlite-database-integration"), &mu.join("sqlite-impl"))?;
    // Site mu-plugins the spawn didn't shadow still need to run.
    if let Ok(site_mu) = std::fs::read_dir(wp_content.join("mu-plugins")) {
        for k in site_mu.flatten() {
            let n = k.file_name();
            if k.path().is_file() && !mu.join(&n).exists() {
                let _ = symlink_dir(&k.path(), &mu.join(&n));
            }
        }
    }

    // db.php drop-in at wp-content/db.php — WP's require_wp_db picks it up.
    // It resolves `__DIR__/../database/…` paths inside the impl dir, so we
    // write a thin loader pointing at the vendored impl.
    std::fs::write(
        content.join("db.php"),
        format!(
            "<?php\nrequire_once '{}';\nrequire_once '{}';\n",
            templates.join("wp-sqlite/sqlite-database-integration/constants.php").display(),
            templates.join("wp-sqlite/sqlite-database-integration/wp-includes/sqlite/db.php").display(),
        ),
    )?;
    // `FQDBDIR` (DB dir): disposable per-spawn sqlite storage.
    let db_dir = dir.join("db");
    std::fs::create_dir_all(&db_dir)?;
    symlink_dir(&db_dir, &content.join("database"))?;
    let wp_db = db_dir.clone();

    // `seeded_post` must reflect a seed that actually landed —
    // `project_post` returns false when the post isn't in rpress.db;
    // claiming it anyway would poison the skip-reseed check.
    let seeded_post = match post_id {
        Some(id) => {
            // Seed goes into the DOCROOT's wp-content — never `www/wp-content`
            // (the site static server exposes that tree verbatim; a seed
            // there would leak draft content + builder meta unauthenticated).
            if project_post(rpress_db, &content, id)? { Some(id) } else { None }
        }
        None => None,
    };
    // Housekeeping: older builds wrote the seed into the PUBLIC
    // wp-content tree — remove any leftover so it stops being served.
    let _ = std::fs::remove_dir_all(www.join("wp-content/rpress-seed"));

    let token = format!("{:x}", rand::random::<u128>());
    std::fs::write(dir.join("bridge-token"), &token)?;
    let port = free_port()?;

    // Theme + element-provider plugins — same DB/dump resolution as playground.
    let (mut theme, mut plugins_json) = (None, None);
    if let Ok(c) = crate::db::conn(rpress_db) {
        let dump = www.parent().map(|w| w.join("dump.sql"));
        let opt = |key: &str| -> Option<String> {
            let row: Option<String> = c.query_row(sql!("intake__select_setting"), [key], |r| r.get(0)).ok()
                .filter(|s: &String| !s.trim().is_empty());
            match row {
                Some(v) => Some(v),
                None => {
                    let v = option_from_dump(dump.as_deref(), key);
                    if let Some(v) = &v {
                        let _ = c.execute(sql!("import__insert_or_replace"), rusqlite::params![key, v]);
                    }
                    v
                }
            }
        };
        theme = opt("stylesheet");
        if let Some(raw) = opt("active_plugins") {
            if let Ok(list) = crate::php_serialize::unserialize(raw.as_bytes()) {
                if let serde_json::Value::Array(items) = list {
                    let mut active: Vec<String> = items.iter()
                        .filter_map(|v| v.as_str().map(|s| s.to_string()))
                        .filter(|p| p.as_str() != plugin_file)
                        .filter(|p| p.split('/').next().map(|d| dir_provides_pb_element(&wp_content.join("plugins").join(d))).unwrap_or(false))
                        .collect();
                    active.sort();
                    active.dedup();
                    if !active.is_empty() {
                        plugins_json = Some(serde_json::to_string(&active).unwrap());
                    }
                }
            }
        }
    }

    let cfg = wp_config(&token, plugin_file, theme.as_deref(), plugins_json.as_deref(), port, &db_dir, &secret)
        .replace("{DOCROOT}", &docroot.display().to_string());
    std::fs::write(docroot.join("wp-config.php"), cfg)?;
    // Identity probe must be a real .php file: php -S does not run
    // extensionless `/__rpress_ident` through WP (empty reply → spawn fail).
    // Token compared here so a stolen port still 403s. GDLR uses the same probe.
    std::fs::write(
        docroot.join("__rpress_ident.php"),
        format!(
            "<?php\n$tok={tok};\n$got=$_SERVER['HTTP_X_RPRESS_BRIDGE']??'';\nif($tok===''||!hash_equals($tok,$got)){{http_response_code(403);exit;}}\nheader('X-Rpress-Ident: bridge');\nhttp_response_code(204);\n",
            tok = php_str(&token),
        ),
    )?;

    let php_args = [
        "-d".to_string(), "opcache.enable_cli=1".to_string(),
        "-d".to_string(), "opcache.jit=tracing".to_string(),
        "-d".to_string(), "opcache.jit_buffer_size=32M".to_string(),
        "-d".to_string(), "opcache.validate_timestamps=0".to_string(),
        "-d".to_string(), "realpath_cache_size=2M".to_string(),
        "-d".to_string(), "realpath_cache_ttl=600".to_string(),
        "-d".to_string(), format!("error_log={}", db_dir.join("php-errors.log").display()),
        "-d".to_string(), "display_errors=0".to_string(),
        "-S".to_string(), format!("127.0.0.1:{port}"), "-t".to_string(), docroot.display().to_string(),
    ];
    let _t0 = Instant::now();
    let child = match sandboxed(&php, &docroot, www, templates, &db_dir) {
        Some(mut c) => {
            let log = std::fs::File::create(dir.join("php.log")).with_context(|| "create bridge php.log")?;
            c.args(&php_args).stdout(Stdio::null()).stderr(Stdio::from(log)).spawn().context("spawn sandboxed php -S")?
        }
        None => {
            // No Seatbelt and no bwrap on this host — a bare `php -S` runs
            // with the rpress user's full fs + network. Fail CLOSED: refuse
            // unless the operator opted in explicitly. On Linux the deploy
            // unit (ProtectHome/ProtectSystem/IPAddressAllow=localhost in
            // install.sh) is the intended confinement; set
            // RPRESS_BRIDGE_UNSAFE=1 to run without any sandbox anyway.
            anyhow::ensure!(
                std::env::var_os("RPRESS_BRIDGE_UNSAFE").is_some_and(|v| v == "1"),
                "bridge: no sandbox tool (sandbox-exec/bwrap) on this host — \
                 refusing unsandboxed `php -S`; set RPRESS_BRIDGE_UNSAFE=1 to override"
            );
            eprintln!(
                "bridge: WARNING — RPRESS_BRIDGE_UNSAFE=1; php -S for {slug} is UNSANDBOXED \
                 (full fs + network of the rpress user)."
            );
            let log = std::fs::File::create(dir.join("php.log")).with_context(|| "create bridge php.log")?;
            Command::new(&php).args(&php_args).stdout(Stdio::null()).stderr(Stdio::from(log)).spawn().context("spawn php -S")?
        }
    };
    // Pidfile BEFORE the probe loop + wp_install: a mid-spawn crash leaves
    // a tracked child `reap_stale_pidfile` can kill (format `pid:port`).
    // Per-pid name — a losing spawn race can never clobber the winner's.
    let pidfile = pidfile_path(www, slug, child.id());
    let _ = std::fs::write(&pidfile, format!("{}:{port}\n", child.id()));

    // php -S boots near-instantly vs the WASM cold start; still probe with
    // the same deadline pattern.
    let deadline = Instant::now() + std::time::Duration::from_secs(15);
    while Instant::now() < deadline {
        if http::probe(port) {
            break;
        }
        std::thread::sleep(std::time::Duration::from_millis(60));
    }
    anyhow::ensure!(http::probe(port), "php -S never came up on 127.0.0.1:{port}");

    // WP install: CLI `wp_install()` on a fresh wp.db (~0.3s) instead of
    // the install.php HTTP wizard — the wizard spends ~14s retrying
    // wp_remote_get (version check, theme files, cron) inside the sandbox.
    // Guard on `wp_options.siteurl` so respawns against a seeded wp.db skip.
    let fqdb = php_str(&format!("{}/wp.db", db_dir.display()));
    let token_php = php_str(&token); // quoted PHP literal for the install snippet — the header token stays raw
    let install_php = format!(
        "<?php\n\
         define('DB_ENGINE','sqlite'); define('FQDB',{fqdb});\n\
         define('DB_NAME','wordpress'); define('DB_USER',''); define('DB_PASSWORD',''); define('DB_HOST','localhost');\n\
         define('DB_CHARSET','utf8'); define('DB_COLLATE','');\n\
         define('WP_HOME','http://127.0.0.1:{port}'); define('WP_SITEURL','http://127.0.0.1:{port}');\n\
         define('ABSPATH', __DIR__ . '/');\n\
         define('WP_CONTENT_DIR', __DIR__ . '/wp-content');\n\
         define('WP_CONTENT_URL','http://127.0.0.1:{port}/wp-content');\n\
         define('WP_PLUGIN_DIR',WP_CONTENT_DIR.'/plugins'); define('WP_PLUGIN_URL','http://x');\n\
         define('WPMU_PLUGIN_DIR',WP_CONTENT_DIR.'/mu-plugins'); define('WPMU_PLUGIN_URL','x');\n\
         define('UPLOADS','wp-content/uploads');\n\
         define('RPRESS_BRIDGE_TOKEN',{token_php}); define('RPRESS_BRIDGE_PLUGIN',{plugin});\n\
         define('RPRESS_BRIDGE_THEME',{theme});\n\
         define('WP_INSTALLING',true);\n\
         $table_prefix='wp_';\n\
         $_SERVER['HTTP_HOST']='127.0.0.1';\n\
         $_SERVER['REQUEST_URI']='/';\n\
         $_SERVER['REQUEST_METHOD']='GET';\n\
         $_SERVER['HTTP_X_RPRESS_BRIDGE']={token_php};\n\
         require ABSPATH . 'wp-settings.php';\n\
         if (get_option('siteurl') !== WP_HOME || get_option('blogname') === '') {{\n\
             require_once ABSPATH . 'wp-admin/includes/upgrade.php';\n\
             wp_install('rpress bridge','admin','admin@bridge.local',false,'',RPRESS_BRIDGE_TOKEN);\n\
         }}\n\
         require_once ABSPATH . 'wp-admin/includes/plugin.php';\n\
         if (RPRESS_BRIDGE_PLUGIN !== '' && file_exists(WP_PLUGIN_DIR . '/' . RPRESS_BRIDGE_PLUGIN)) {{\n\
             activate_plugin(RPRESS_BRIDGE_PLUGIN);\n\
         }}\n\
         if (defined('RPRESS_BRIDGE_PLUGINS')) {{\n\
             foreach ((array) json_decode(RPRESS_BRIDGE_PLUGINS, true) as $rpress_p2) {{\n\
                 if (is_string($rpress_p2) && $rpress_p2 !== RPRESS_BRIDGE_PLUGIN && file_exists(WP_PLUGIN_DIR . '/' . $rpress_p2)) {{\n\
                     activate_plugin($rpress_p2);\n\
                 }}\n\
             }}\n\
         }}\n\
         $rpress_theme = defined('RPRESS_BRIDGE_THEME') ? RPRESS_BRIDGE_THEME : '';\n\
         if ($rpress_theme !== '' && get_option('stylesheet') !== $rpress_theme) {{\n\
             switch_theme($rpress_theme);\n\
         }}\n\
         $rpress_seed = WP_CONTENT_DIR . '/rpress-seed/post.json';\n\
         if (file_exists($rpress_seed) && !get_option('rpress_post_seeded')) {{\n\
             $rpress_j = json_decode(file_get_contents($rpress_seed), true);\n\
             $rpress_p = is_array($rpress_j) ? ($rpress_j['post'] ?? null) : null;\n\
             if (is_array($rpress_p) && (empty($rpress_p['ID']) || !get_post((int) $rpress_p['ID']))) {{\n\
                 $rpress_pid = wp_insert_post([\n\
                     'import_id'    => isset($rpress_p['ID']) ? (int) $rpress_p['ID'] : 0,\n\
                     'post_title'   => $rpress_p['post_title'] ?? '',\n\
                     'post_content' => $rpress_p['post_content'] ?? '',\n\
                     'post_excerpt' => $rpress_p['post_excerpt'] ?? '',\n\
                     'post_status'  => $rpress_p['post_status'] ?? 'draft',\n\
                     'post_name'    => $rpress_p['post_name'] ?? '',\n\
                     'post_type'    => $rpress_p['post_type'] ?? 'page',\n\
                 ], true);\n\
                 if (!is_wp_error($rpress_pid)) {{\n\
                     update_option('rpress_post_seeded', $rpress_pid, false);\n\
                     if (!empty($rpress_j['meta']) && is_array($rpress_j['meta'])) {{\n\
                         foreach ($rpress_j['meta'] as $rpress_mk => $rpress_mv) {{\n\
                             update_post_meta($rpress_pid, $rpress_mk, $rpress_mv);\n\
                         }}\n\
                     }}\n\
                 }}\n\
             }}\n\
             update_option('rpress_seed_done', 1, false);\n\
         }}\n",
        theme = php_str(theme.as_deref().unwrap_or("")),
        plugin = php_str(plugin_file),
    );
    let install_path = docroot.join("rpress-install.php");
    std::fs::write(&install_path, &install_php)?;
    // Skeleton wp.db: run the install once ever, cache outside <slug>
    // (spawn wipes that dir). Seed ALWAYS runs via rpress-install.php so a
    // skel copy still inserts the current post_id.
    let skel = www.join("bridge").join(format!(".skel-{slug}.db"));
    if skel.is_file() {
        std::fs::copy(&skel, db_dir.join("wp.db")).context("copy wp.db skeleton")?;
        if let Ok(c) = crate::db::conn(&db_dir.join("wp.db")) {
            let _ = c.execute(sql!("bridge_php_cgi__delete_seed_options"), []);
        }
    }
    let install_args = [
        "-d".to_string(), "opcache.enable_cli=1".to_string(),
        "-d".to_string(), "display_errors=1".to_string(),
        install_path.display().to_string(),
    ];
    match sandboxed(&php, &docroot, www, templates, &db_dir) {
        Some(mut c) => {
            let o = c.current_dir(&docroot).args(&install_args).output().context("WP install")?;
            anyhow::ensure!(o.status.success(), "WP install exit {} stderr {}", o.status, String::from_utf8_lossy(&o.stderr));
        }
        None => {
            let o = Command::new(&php).current_dir(&docroot).args(&install_args).output().context("WP install")?;
            anyhow::ensure!(o.status.success(), "WP install exit {} stderr {}", o.status, String::from_utf8_lossy(&o.stderr));
        }
    }
    if !skel.is_file() {
        let _ = std::fs::copy(db_dir.join("wp.db"), &skel);
    }

    // Warm-up: the FIRST admin-ajax after a fresh install carries
    // activation/install transients (traveltour theme_landing redirects
    // and similar welcome hooks answer it with 302/400). Absorb it here
    // — before `spawn()` returns — so a user's click is never that
    // request. Without this the editor's first element click after every
    // spawn or idle-reap saw "An error occurs".
    {
        let mut fwd: Vec<(String, String)> = Vec::new();
        fwd.push(("X-Rpress-Bridge".to_string(), token.clone()));
        let _ = http::request(
            port,
            "POST",
            "/wp-admin/admin-ajax.php",
            &fwd,
            b"action=rpress_warmup",
        );
    }

    Ok(BridgeState {
        rt: Box::new(PhpCgi { child, port }),
        last_used: Instant::now(),
        spawned_at: Instant::now(),
        token,
        wp_db,
        pidfile,
        seeded_post,
    })
}
