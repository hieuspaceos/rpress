//! `RuntimeKind::PhpCgi` — `php -S` built-in server hosting a real WP
//! docroot. ~100–200MB instead of the ~1.2GB WASM playground; same
//! `PhpRuntime` contract (HTTP on 127.0.0.1:<port>).
//!
//! Docroot layout (built per spawn under `www/bridge/<slug>/docroot/`):
//!   wp-* core files  → copied from `templates/wp-core/` (vendored WP 6.7)
//!   wp-content/      → symlink farm: site plugins/themes/uploads per-child,
//!                      bundled `templates/wp-plugins/*` fallback, `database/`
//!                      → `db_dir` (sqlite drop-in storage), `db.php` drop-in
//!                      + `sqlite/` impl vendored from `templates/wp-sqlite/`
//!   wp-config.php    → rendered template (constants the playground passes
//!                      via `--define` live here instead)
//!
//! `php -S` is single-worker — requests serialize, which suits the
//! single-admin edit flow; the entry mutex already serializes bridge
//! traffic per key.

use super::*;
use super::playground::{dir_provides_pb_element, free_port, option_from_dump, project_post, MU_PLUGIN};
use anyhow::{Context, Result};
use std::path::Path;
use std::process::{Child, Command, Stdio};

pub(crate) struct PhpCgi {
    child: Child,
    port: u16,
}

impl PhpRuntime for PhpCgi {
    fn request(&mut self, method: &str, path: &str, headers: &[(String, String)], body: &[u8]) -> Result<BridgeResponse> {
        http::request(self.port, method, path, headers, body)
    }
    fn healthy(&mut self, token: &str) -> bool {
        self.child.try_wait().map(|s| s.is_none()).unwrap_or(false) && http::probe_identity(self.port, token)
    }
    fn kill(&mut self) {
        let _ = self.child.kill();
        let _ = self.child.wait();
    }
    fn pid(&self) -> u32 {
        self.child.id()
    }
}

impl Drop for PhpCgi {
    fn drop(&mut self) {
        self.kill();
    }
}

/// `php` on PATH, else common brew/apt locations.
pub(crate) fn php_bin() -> Option<PathBuf> {
    for c in [PathBuf::from("php"), PathBuf::from("/opt/homebrew/bin/php"), PathBuf::from("/usr/local/bin/php"), PathBuf::from("/usr/bin/php")] {
        // PATH lookup for the bare name: spawn a probe.
        if c == PathBuf::from("php") {
            if Command::new("php").arg("-v").stdout(Stdio::null()).stderr(Stdio::null()).status().map(|s| s.success()).unwrap_or(false) {
                return Some(c);
            }
        } else if c.is_file() {
            return Some(c);
        }
    }
    None
}

/// Materialize `src` → `dst`: hardlinks for regular files (shared inode
/// with `templates/wp-core` — zero copy cost per spawn, WP never rewrites
/// core files), dirs created. Falls back to copy across filesystems.
fn cp_r(src: &Path, dst: &Path) -> Result<()> {
    std::fs::create_dir_all(dst)?;
    for e in std::fs::read_dir(src)?.flatten() {
        let (s, d) = (e.path(), dst.join(e.file_name()));
        let ft = e.file_type()?;
        if ft.is_dir() {
            cp_r(&s, &d)?;
        } else if ft.is_file() {
            if std::fs::hard_link(&s, &d).is_err() {
                std::fs::copy(&s, &d)?;
            }
        }
    }
    Ok(())
}

fn symlink_dir(src: &Path, dst: &Path) -> Result<()> {
    #[cfg(unix)]
    std::os::unix::fs::symlink(src, dst)?;
    Ok(())
}

/// Rendered `wp-config.php` — constants the playground passes via
/// `--define`/consts.json plus sqlite + URL wiring.
